CREATE TABLE IF NOT EXISTS sp_api_endpoint (
  id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  c_name VARCHAR(200) NOT NULL,
  c_uri VARCHAR(500) NOT NULL,
  c_method VARCHAR(10) NOT NULL DEFAULT 'POST',
  c_query TEXT NOT NULL,
  c_database VARCHAR(128) NULL,
  c_field_map TEXT NULL,
  i_active TINYINT(1) NOT NULL DEFAULT 1,
  d_last_sent DATETIME NULL,
  c_created_by VARCHAR(100) NULL,
  d_created DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  d_updated DATETIME NULL ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
